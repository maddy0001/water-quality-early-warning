"""Operations Console: recorded utility data replayed minute by minute, with the user as the operator.

Layout rules that keep the page calm while it updates:
  * every chart has a fixed key and size, so it is updated in place instead of being rebuilt;
  * the review panel is always present (empty when nothing awaits review), so nothing jumps;
  * reports and downloads live outside the live area and only change on a click.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st
from plotly.subplots import make_subplots

from ewsv2.app import charts as C
from ewsv2.app import export as X
from ewsv2.app import services as S
from ewsv2.app import ui
from ewsv2.app.views.common import base, board, llm_status, sources

WINDOW = 720           # minutes shown in the charts (12 hours)
SPEEDS = [1, 5, 15, 60, 240]
MAX_JUMP = 30000       # "Skip to next alarm" gives up after this many minutes (about 3 weeks)


def _state() -> S.ReplayState | None:
    return st.session_state.get("cr_state")


def _restart(source: str) -> None:
    st.session_state["cr_state"] = S.ReplayState(**base(source))
    st.session_state["cr_reports"] = {}
    st.session_state["cr_play"] = False
    b = board(connect=False)
    if st.session_state.get("cr_uno") and b is not None and b.connected:
        b.configure_edge(True, True)


def _board_if(uno: bool):
    return board(connect=False) if uno else None


def render() -> None:
    ui.header("Operations Console",
              "Replays recorded utility data minute by minute, as if it were arriving live. The system raises "
              "alarms; you review each one as the control-room operator.", kicker="Monitor · replay", color="ocean")
    srcs = sources()
    b = board()
    uno_ok = b is not None and b.connected

    with st.container(border=True):
        ui.panel_title("Control panel")
        c1, c2 = st.columns([2, 1.2])
        with c1:
            source = st.selectbox("Data source", srcs, key="cr_source_pick", format_func=S.source_label)
            ui.cap("Which recorded data to replay. Utility data A and B are real measurements from a German "
                   "drinking-water utility (public GECCO datasets); the synthetic station is generated by the "
                   "computer and always available.")
        with c2:
            speed = st.select_slider("Replay speed", options=SPEEDS, value=5, key="cr_speed",
                                     format_func=lambda v: f"{v} min per second")
            ui.cap("How much station time passes per second while the replay is running.")
        playing = st.session_state.get("cr_play", False)
        b1, b2, b3, b4 = st.columns(4)
        with b1:
            if st.button("Pause replay" if playing else "Start replay", width="stretch", type="primary",
                         icon=":material/pause:" if playing else ":material/play_arrow:", key="cr_btn_play"):
                st.session_state["cr_play"] = not playing
                st.rerun()
            ui.cap("Runs the data continuously. Stops by itself when an alarm needs your review.")
        with b2:
            jump = st.button("Skip to next alarm", width="stretch", icon=":material/skip_next:", key="cr_btn_jump")
            ui.cap("Fast-forwards until the next alarm has occurred and ended. The quickest way to demonstrate.")
        with b3:
            step1 = st.button("Advance one minute", width="stretch", icon=":material/arrow_forward:", key="cr_btn_step")
            ui.cap("Processes exactly one more minute of data.")
        with b4:
            restart = st.button("Restart", width="stretch", icon=":material/restart_alt:", key="cr_btn_restart")
            ui.cap("Returns to the first minute of the test period and clears all reviews.")
        with st.expander("Advanced options"):
            o1, o2, o3 = st.columns(3)
            with o1:
                reveal = st.toggle("Show recorded outcome", value=True, key="cr_reveal")
                ui.cap("Shows what actually happened in the data (a utility-labelled event, injected contamination "
                       "or an injected sensor fault). The detection system never sees this; it is shown so you can "
                       "judge whether each alarm was right.")
            with o2:
                auto = st.toggle("Automatic review", value=False, key="cr_auto")
                ui.cap("Classifies every alarm automatically from the recorded outcome instead of asking you. The "
                       "replay then never pauses for review.")
            with o3:
                uno = st.toggle("Verify on Arduino", value=False, disabled=not uno_ok, key="cr_uno_toggle")
                ui.cap("Sends every minute to the connected Arduino and checks that it reaches exactly the same "
                       "decision as the laptop. " + ("" if uno_ok else "Not available: no Arduino connected."))
    verdict_mode = "auto" if auto else "you"

    if uno != st.session_state.get("cr_uno", False):
        st.session_state["cr_uno"] = uno
        st.session_state.pop("cr_state", None)              # both start fresh so their states match
    if _state() is None or st.session_state.get("cr_source") != source:
        st.session_state["cr_source"] = source
        _restart(source)
    if uno:
        speed = min(speed, 15)
    if restart:
        _restart(source)
    if jump:
        st.session_state["cr_play"] = False
        with st.spinner("Searching for the next alarm …"):
            st.session_state["cr_jump"] = _next_alarm(verdict_mode, uno)
    if step1:
        _advance(1, verdict_mode, uno)

    run_every = 1.0 if st.session_state.get("cr_play") else None

    @st.fragment(run_every=run_every)
    def live() -> None:
        state = _state()
        if state is None:
            return
        if st.session_state.get("cr_play") and state.pending is None and not state.done:
            _advance(speed, verdict_mode, uno)
        _view(state, reveal, uno, verdict_mode, speed)

    live()
    _below(_state(), reveal)


# --------------------------------------------------------------------------------------------- moving in time

def _advance(n: int, mode: str, uno: bool) -> None:
    state = _state()
    if state is None:
        return
    b = _board_if(uno)
    for _ in range(n):
        if state.step(mode, b) is None:
            break


def _next_alarm(mode: str, uno: bool) -> str:
    """Run until an alarm (water alarm or sensor alert) has happened and ended. Returns a short note."""
    state = _state()
    if state is None or state.pending is not None:
        return ""
    b = _board_if(uno)
    asks0, n0 = state.asks, len(state.episodes)
    limit = 3000 if uno else MAX_JUMP
    for _ in range(limit):
        row = state.step(mode, b)
        if row is None:                                   # waiting for the operator, or the data ended
            break
        if state.asks > asks0:                            # an alarm cycle ended (automatic review answered it)
            break
        new = state.episodes[n0:]
        if new and all(e["kind"] == "sensor" for e in new) and row["i"] - new[-1]["end"] > 5:
            break                                         # a sensor alert happened and ended
    else:
        return f"No alarm in the next {limit:,} minutes. Select Skip to next alarm again to keep searching."
    if state.done and state.pending is None:
        return "The end of the test period has been reached. Select Restart to begin again."
    return ""


# --------------------------------------------------------------------------------------------- the live area

def _view(state: S.ReplayState, reveal: bool, uno: bool, mode: str, speed: int) -> None:
    rows = state.rows[-WINDOW:]
    if state.done:
        doing = "Finished"
    elif state.pending is not None:
        doing = "Waiting for your review"
    else:
        doing = "Running" if st.session_state.get("cr_play") else "Paused"
    now = rows[-1]["time"] if rows else state.frame.index[state.start]
    ui.meta([("Data source", S.source_label(st.session_state.get("cr_source", state.name), short=True)),
             ("Station time", f"{now:%d %b %Y, %H:%M}"),
             ("Replayed", f"{state.pos / 1440:.1f} days ({state.pos:,} minutes)"),
             ("Replay", doing), ("Speed", f"{speed} min/s")])
    note = st.session_state.pop("cr_jump", "")
    if note:
        st.info(note)

    if not rows:
        ui.state("idle", "Ready", "Select Skip to next alarm (fastest) or Start replay. The replay begins at the first "
                 f"minute of the test period ({state.frame.index[state.start]:%d %b %Y, %H:%M}).")
    else:
        _state_bar(state, rows[-1])
    _tiles(state, uno)
    _review(state, reveal, uno, mode)

    last = rows[-1] if rows else None
    g, t = st.columns([1, 2.4])
    with g:
        theta = float(state.engine.theta) if np.isfinite(state.engine.theta) else float(state.spec["theta0"])
        score = last["logit"] if last is not None and np.isfinite(last["logit"]) else -10.0
        C.gauge(score, -10, 15, "anomaly score", key="cr_gauge",
                stops=[(theta, ui.OK), (min(15, theta + 3), ui.WARN), (15, ui.BAD)], height=300)
        ui.cap(f"Green zone ends at the alarm threshold ({theta:+.2f}). The needle entering the red zone means "
               "the water looks more unusual than the threshold allows.")
    with t:
        C.plot(_timeline(rows, reveal), key="cr_timeline", steady=True)
        ui.cap("Blue: anomaly score each minute. Dashed: alarm threshold – it steps up after every alarm you mark as "
               "false and then slowly returns. Red dots: water-quality alarm; amber diamonds: sensor-fault alert."
               + (" Shaded bands: recorded outcome." if reveal else ""))
    p, lg = st.columns([1, 1.35])
    with p:
        C.plot(_polar(last, state.sensors), key="cr_polar", steady=True)
        ui.cap("How far each sensor changed in the last 15 minutes, relative to its largest change in normal "
               "operation. Bars beyond the dashed ring (1.0) are outside normal behaviour.")
    with lg:
        _log_table(state, reveal)
    with st.expander(f"Sensor readings – all {len(state.sensors)} sensors, last 12 hours"):
        C.plot(_sensor_grid(rows, state), key="cr_sens", steady=True)
        ui.cap("Amber diamonds mark minutes where that sensor failed a health check (stuck, dropped out or "
               "spiking); its value was excluded from the water assessment.")


def _state_bar(state: S.ReplayState, last: dict) -> None:
    names = state.sensors
    flagged = [names[j] for j in range(len(names)) if last["mask"] >> j & 1]
    if last["water"]:
        top = names[last["top"]]
        ui.state("water", "Water-quality alarm",
                 f"{S.SENSOR_NAMES.get(top, top).capitalize()} ({top}) changed {last['m'][last['top']]:.1f} times its "
                 "largest normal 15-minute change. The water itself is behaving abnormally."
                 + (f" A sensor-fault alert is active at the same time ({', '.join(flagged)})." if flagged else ""))
    elif last["sensor"]:
        ui.state("sensor", "Sensor-fault alert: " + ", ".join(flagged),
                 "This sensor behaves like a failing instrument while the other sensors show normal water. "
                 "Action: maintenance. No water-quality alarm is raised.")
    elif last["alarm"]:
        ui.state("sensor", "Alarm suppressed",
                 "The anomaly score crossed the threshold, but the change came only from a sensor that failed its "
                 "health check.")
    else:
        ui.state("normal", "Normal operation",
                 f"All {len(names)} sensors are healthy and the water is within its normal behaviour.")


def _tiles(state: S.ReplayState, uno: bool) -> None:
    eps = state.episodes
    water = [e for e in eps if e["kind"] == "water"]
    sensor = [e for e in eps if e["kind"] == "sensor"]
    real = sum(1 for e in water if e["truth"])
    theta0 = float(state.spec["theta0"])
    theta = float(state.engine.theta)
    lifted = theta - theta0 if np.isfinite(theta) else 0.0
    right = sum(a["right"] for a in state.answers)
    items = [
        ("Water-quality alarms", str(len(water)), f"{real} matched a recorded event · {len(water) - real} did not",
         "red"),
        ("Sensor-fault alerts", str(len(sensor)), "sent to maintenance, no public alarm", "amber"),
        ("Review accuracy", f"{right} / {len(state.answers)}" if state.answers else "–",
         "your reviews that match the recorded outcome" if state.answers else "no alarms reviewed yet", "violet"),
        ("Alarm threshold", "–" if not np.isfinite(theta) else f"{theta:+.2f}",
         "at its starting value" if abs(lifted) < 0.05 else
         (f"{lifted:+.2f} from start: less sensitive" if lifted > 0 else f"{lifted:+.2f} from start: more sensitive"),
         "indigo"),
    ]
    if uno:
        items.append(("Arduino agreement", f"{state.uno_same:,} / {state.uno_checked:,}",
                      state.uno_note or "minutes with identical decisions", "ocean"))
    ui.tiles(items)


def _review(state: S.ReplayState, reveal: bool, uno: bool, mode: str) -> None:
    """The alarm review panel. Always the same size, so the page below does not jump."""
    p = state.pending
    with st.container(border=True, height=170, key="review_open" if p is not None else "review_idle"):
        ui.panel_title("Alarm review")
        if p is None:
            if mode == "auto":
                st.markdown("Automatic review is on: every alarm is classified from the recorded outcome and the "
                            "replay does not pause. Turn it off under *Advanced options* to review alarms yourself.")
            else:
                st.markdown("No alarm is waiting for review. When an alarm ends, the replay pauses here and asks "
                            "whether it was a real water-quality event.")
                last = state.answers[-1] if state.answers else None
                if last:
                    verdict = "matches" if last["right"] else "does not match"
                    lift = last.get("lift", 0.0)
                    eff = (f"The alarm threshold was raised by {lift:.2f}, so the system is now slightly less "
                           "sensitive." if lift > 0 else "The alarm threshold was kept unchanged.")
                    said = "real event" if last["said"] == "real event" else "false alarm"
                    st.caption(f"Last review: alarm at {state.frame.index[last['start']]:%d %b %H:%M} marked as "
                               f"**{said}** – this {verdict} the recorded outcome. {eff}")
            return
        a, z = p["ep_start"], p["last_on"]
        st.markdown(f'<div class="review">The alarm from {state.frame.index[a]:%d %b %H:%M} to '
                    f'{state.frame.index[z]:%H:%M} has ended. Was it a real water-quality event?</div>',
                    unsafe_allow_html=True)
        q1, q2, q3 = st.columns([1, 1, 2.2], vertical_alignment="center")
        q1.button("Confirm as real event", width="stretch", key="cr_real", type="primary",
                  icon=":material/check_circle:", on_click=_answer, args=(False, uno))
        q2.button("Mark as false alarm", width="stretch", key="cr_false", icon=":material/cancel:",
                  on_click=_answer, args=(True, uno))
        if reveal:
            what = p["truth"] or "no event – the water was normal"
            right = "Confirm as real event" if p["key"] == "real event" else "Mark as false alarm"
            q3.markdown(f'{ui.badge("Recorded outcome", "violet")} {ui.esc(what)}<br>'
                        f'<span class="muted">Correct review: <b>{right}</b>. Marking as false alarm raises the '
                        f'threshold by 0.5.</span>', unsafe_allow_html=True)
        else:
            q3.caption("Recorded outcome hidden (Advanced options → Show recorded outcome). Marking as false alarm "
                       "raises the threshold by 0.5.")


def _answer(false_alarm: bool, uno: bool) -> None:
    state = _state()
    if state is not None:
        state.answer(false_alarm, _board_if(uno))


# --------------------------------------------------------------------------------------------- charts

def _timeline(rows, reveal) -> go.Figure:
    t = [r["time"] for r in rows]
    fig = go.Figure()
    if reveal and rows:
        cls = np.array([r["cls"] for r in rows])
        for code, color, name in ((1, "rgba(220,38,38,.13)", "recorded water event"),
                                  (2, "rgba(217,119,6,.16)", "recorded sensor fault")):
            y = np.where(cls == code, 16, None)
            fig.add_trace(go.Scatter(x=t, y=y, fill="tozeroy", mode="none", fillcolor=color, name=name,
                                     hoverinfo="skip"))
    fig.add_trace(go.Scatter(x=t, y=[-10] * len(t), mode="lines", line=dict(width=0), showlegend=False,
                             hoverinfo="skip"))
    fig.add_trace(go.Scatter(x=t, y=[r["logit"] for r in rows], name="anomaly score", fill="tonexty",
                             fillcolor="rgba(79,70,229,.12)", line=dict(width=1.8, color=ui.ACCENT)))
    fig.add_trace(go.Scatter(x=t, y=[r["theta"] for r in rows], name="alarm threshold",
                             line=dict(width=2.2, color="#e11d48", dash="dash")))
    wt = [r["time"] for r in rows if r["water"]]
    st_ = [r["time"] for r in rows if r["sensor"]]
    fig.add_trace(go.Scatter(x=wt, y=[14] * len(wt), mode="markers", name="water-quality alarm",
                             marker=dict(color=ui.BAD, size=7)))
    fig.add_trace(go.Scatter(x=st_, y=[-9] * len(st_), mode="markers", name="sensor-fault alert",
                             marker=dict(color=ui.WARN, size=7, symbol="diamond")))
    fig.update_layout(height=330, title="Anomaly score and alarm threshold – last 12 hours",
                      yaxis=dict(range=[-11, 16], title="anomaly score"), legend=dict(orientation="h", y=-0.2, x=0))
    return fig


def _polar(last, names) -> go.Figure:
    m = last["m"] if last is not None else np.zeros(len(names))
    r = [float(min(v, 6)) for v in m]
    colors = [ui.BAD if v >= 1 else ui.SERIES[i % len(ui.SERIES)] for i, v in enumerate(m)]
    top = max(r) if r else 0
    rmax = 1.6 if top < 1.4 else (3 if top < 2.7 else 6.2)
    fig = go.Figure()
    fig.add_trace(go.Barpolar(r=r, theta=list(names), marker=dict(color=colors, line=dict(color="#fff", width=1)),
                              opacity=0.9, name="change", hovertemplate="%{theta}: %{r:.2f}×<extra></extra>"))
    fig.add_trace(go.Scatterpolar(r=[1] * (len(names) + 1), theta=list(names) + [names[0]], mode="lines",
                                  line=dict(color="#e11d48", dash="dash", width=1.5), name="largest normal change",
                                  hoverinfo="skip"))
    fig.update_layout(height=340, title="Which sensors changed (last 15 minutes)", showlegend=False,
                      polar=dict(radialaxis=dict(range=[0, rmax], showticklabels=True, tickfont=dict(size=9),
                                                 gridcolor="#e2e7f1"),
                                 angularaxis=dict(gridcolor="#e2e7f1"), bgcolor="rgba(0,0,0,0)"),
                      margin=dict(l=30, r=30, t=50, b=20))
    return fig


def _sensor_grid(rows, state) -> go.Figure:
    k = len(state.sensors)
    ncol = 3
    nrow = int(np.ceil(k / ncol))
    fig = make_subplots(rows=nrow, cols=ncol, shared_xaxes=True, vertical_spacing=0.09, horizontal_spacing=0.05,
                        subplot_titles=[f"{s} · {S.SENSOR_NAMES.get(s, s)}" for s in state.sensors])
    f = state.frame.iloc[rows[0]["i"]:rows[-1]["i"] + 1] if rows else state.frame.iloc[0:0]
    for j, s in enumerate(state.sensors):
        rr, cc = j // ncol + 1, j % ncol + 1
        col = ui.SERIES[j % len(ui.SERIES)]
        fig.add_trace(go.Scatter(x=f.index, y=f[s], line=dict(width=1.3, color=col), fill="tozeroy",
                                 fillcolor=C.alpha(col, 0.08), showlegend=False, name=s), row=rr, col=cc)
        flagged = [r["time"] for r in rows if r["mask"] >> j & 1]
        fig.add_trace(go.Scatter(x=flagged, y=f[s].reindex(flagged) if flagged else [], mode="markers",
                                 marker=dict(color=ui.WARN, size=6, symbol="diamond"),
                                 showlegend=False, name=f"{s} flagged"), row=rr, col=cc)
    fig.update_layout(height=130 * nrow + 60, margin=dict(l=10, r=10, t=40, b=10))
    fig.update_annotations(font_size=11)
    fig.update_xaxes(nticks=4, tickangle=0, tickformat="%H:%M")
    return fig


def _log_frame(state, reveal: bool = True) -> pd.DataFrame:
    out = []
    for e in state.episodes:
        review = {"confirmed": "Confirmed real", "false alarm": "Marked false"}.get(e["verdict"], "")
        row = {"Start": state.frame.index[e["start"]].strftime("%d %b %Y %H:%M"),
               "Minutes": e["end"] - e["start"] + 1,
               "Type": "Water-quality alarm" if e["kind"] == "water" else "Sensor-fault alert",
               "Sensors": ", ".join(s for j, s in enumerate(state.sensors) if e["mask"] >> j & 1)
               or state.sensors[int(np.argmax(e["peak_m"]))],
               "Review": review or ("–" if e["kind"] == "water" else "not required")}
        if reveal:
            row["Recorded outcome"] = e["truth"] or "no event (normal water)"
        out.append(row)
    return pd.DataFrame(out)


def _log_table(state, reveal) -> None:
    df = _log_frame(state, reveal)
    ui.panel_title("Alarm log")
    if df.empty:
        st.caption("No alarms yet. Select Skip to next alarm.")
        return
    show = df.iloc[::-1].head(50)
    st.dataframe(show, hide_index=True, width="stretch", height=min(300, 38 + 35 * len(show)),
                 column_config={"Minutes": st.column_config.NumberColumn(width="small"),
                                "Type": st.column_config.TextColumn(width="medium")})


# --------------------------------------------------------------------------------------------- below the live area

def _below(state, reveal: bool) -> None:
    """Incident report and downloads. Outside the live area: changes only when you click something."""
    if state is None:
        return
    ui.section("Incident report and downloads",
               "Select an alarm to prepare its incident report, then download it as text or as a printable page.")
    eps = state.episodes
    with st.container(border=True):
        if not eps:
            st.caption("No alarms yet. After the first alarm you can prepare its report here and download the "
                       "alarm log.")
            return
        if st.session_state.get("cr_play"):
            st.caption("The alarm list below was captured when the replay started. Pause the replay to include the "
                       "latest alarms.")
        cfg = S.config()
        labels = {i: (f"{state.frame.index[e['start']]:%d %b %Y %H:%M} – "
                      f"{'water-quality alarm' if e['kind'] == 'water' else 'sensor-fault alert'}")
                  for i, e in enumerate(eps)}
        c1, c2 = st.columns([2, 1.3])
        with c1:
            pick = st.selectbox("Alarm", list(labels)[::-1], format_func=labels.get, key="cr_rep_pick")
            ui.cap("The alarm the report is about. The newest alarm is listed first.")
        with c2:
            llm_ok, _ = llm_status()
            use_llm = st.toggle("Write with the AI model", value=False, key="cr_rep_llm", disabled=not llm_ok)
            ui.cap("Uses the local language model (Ollama) for a more readable report; every fact is checked and a "
                   "report with any error is replaced by the standard template. "
                   + ("" if llm_ok else "Not available: Ollama is not running, so the template is used."))
        rec = S.episode_record(state, eps[pick], f"Monitoring station ({S.source_label(state.name, short=True)})")
        key = (pick, eps[pick]["end"], use_llm)
        cache = st.session_state.setdefault("cr_reports", {})
        if key not in cache:
            with st.spinner("Preparing the report …"):
                cache[key] = S.write_report(rec, state.sensors, use_llm, cfg["llm"]["models"][0], cfg["llm"]["host"])
        rep = cache[key]
        shown = rep["llm"] if rep["shown"] == "llm" else rep["template"]
        writer = f"AI model {cfg['llm']['models'][0]} (fact-checked)" if rep["shown"] == "llm" else "standard template"
        a, b = st.columns([1.5, 1])
        with a:
            st.markdown(f'<div class="report">{ui.esc(shown)}</div>', unsafe_allow_html=True)
        with b:
            st.markdown(ui.badge("Written by the AI model · facts verified", "violet") if rep["shown"] == "llm"
                        else ui.badge("Standard template report", "info"), unsafe_allow_html=True)
            if rep["why"] and use_llm:
                st.caption(rep["why"])
            stem = f"incident_{rec['id']}_{rec['start'][:10]}"
            st.download_button("Download report (.txt)", X.report_txt(shown, rec, writer), file_name=stem + ".txt",
                               mime="text/plain", width="stretch", icon=":material/download:", on_click="ignore",
                               key="cr_dl_txt")
            st.download_button("Download printable report (.html)", X.report_html(shown, rec, writer),
                               file_name=stem + ".html", mime="text/html", width="stretch",
                               icon=":material/print:", on_click="ignore", key="cr_dl_html")
            st.download_button("Download alarm log (.csv)", _log_frame(state, True).to_csv(index=False).encode("utf-8"),
                               file_name=f"alarm_log_{state.name}.csv", mime="text/csv", width="stretch",
                               icon=":material/table_view:", on_click="ignore", key="cr_dl_csv")
            ui.cap("The printable report opens in any browser; use Print → Save as PDF for a PDF copy.")
            if rep["errors"]:
                st.dataframe(pd.DataFrame(rep["errors"]), hide_index=True, width="stretch")
            with st.expander("Alarm record (the only facts the report may use)"):
                st.json(rec, expanded=False)
